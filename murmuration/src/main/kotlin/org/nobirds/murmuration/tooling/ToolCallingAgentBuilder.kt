)

/**
 * Retry-safe variant of the [Builder]-based [toolAgent]. Pre-built [Builder] is captured once
 * in the agent closure; every execute (including retries) routes into the same instance.
 * Final output is `tool.build()`.
 */
inline fun <In, reified B : Builder<Out>, Out> toolAgent(
    llm: Llm,
    executor: PromptExecutor,
    name: String = "BuilderAgent",
    maxTurns: Int = 10,
    noinline maxTurnsFn: ((In) -> Int)? = null,
    eventListener: AgentEventListener? = null,
    roundTripRetry: RetryPolicy? = null,
    frameworkInstructionsCacheStrategy: PromptCacheStrategy = PromptCacheStrategy.PIPELINE,
    tool: B,
    crossinline block: suspend PromptBuilder.(ExecutionContext, In, B) -> Unit
): Agent<In, Out> = toolAgent(
    llm, executor, name, maxTurns, maxTurnsFn, eventListener, roundTripRetry,
    frameworkInstructionsCacheStrategy = frameworkInstructionsCacheStrategy,
    factory = { _, _ -> tool },
    block = block,
)

/**
 * Version of [toolAgent] that uses the tool directly without transformation.
 * Useful when the tool itself is the result (e.g., a collector object).
 */
inline fun <In, reified Tool : Any> toolAgent(
    llm: Llm,
    executor: PromptExecutor,
    name: String = "${Tool::class.simpleName}Agent",
    maxTurns: Int = 10,
    noinline maxTurnsFn: ((In) -> Int)? = null,
    eventListener: AgentEventListener? = null,
    roundTripRetry: RetryPolicy? = null,
    frameworkInstructionsCacheStrategy: PromptCacheStrategy = PromptCacheStrategy.PIPELINE,
    crossinline block: suspend PromptBuilder.(ExecutionContext, In, Tool) -> Unit
): Agent<ToolCallingInput<In, Tool>, Tool> = toolCallingAgent(
    llm, executor, name, maxTurns, maxTurnsFn, eventListener, roundTripRetry,
    frameworkInstructionsCacheStrategy = frameworkInstructionsCacheStrategy, block = block,
)
