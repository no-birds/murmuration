inline fun <In, reified B : Builder<Out>, Out> toolAgent(
    llm: Llm,
    executor: PromptExecutor,
    name: String = "BuilderAgent",
    maxTurns: Int = 10,
    noinline maxTurnsFn: ((In) -> Int)? = null,
    eventListener: AgentEventListener? = null,
    roundTripRetry: RetryPolicy? = null,
    frameworkInstructionsCacheStrategy: PromptCacheStrategy = PromptCacheStrategy.PIPELINE,
    crossinline factory: (ExecutionContext, In) -> B,
