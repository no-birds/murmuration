/**
 * Interface for builders used by tool agents.
 */
interface Builder<out T> {
    fun build(): T
}

/**
 * Common interface for tasks generated by planners.
 */
interface Task {
    val id: String
    val description: String
}

inline fun <In, reified Tool: Any> toolCallingAgent(
    llm: Llm,
    executor: PromptExecutor,
    name: String = "ToolCallingAgent",
    maxTurns: Int = 10,
    noinline maxTurnsFn: ((In) -> Int)? = null,
    eventListener: AgentEventListener? = null,
    roundTripRetry: RetryPolicy? = null,
    frameworkInstructionsCacheStrategy: PromptCacheStrategy = PromptCacheStrategy.PIPELINE,
    crossinline block: suspend PromptBuilder.(ExecutionContext, In, Tool) -> Unit,
): Agent<ToolCallingInput<In, Tool>, Tool> = ToolCallingAgent(
    executor,
    PromptGenerator.build(llm) { ec, input -> block(ec, input.input, input.tool) },
    name, maxTurns, maxTurnsFn, eventListener,
    frameworkInstructionsCacheStrategy = frameworkInstructionsCacheStrategy,
    roundTripRetry = roundTripRetry,
)

/**
 * @deprecated Stateful builders should use the `tool = ...` overload below — `factory` here
 * is invoked through `mapInput.transform` on **every** `Agent.execute` call (including
 * retries by [org.nobirds.murmuration.agent.RetryAgent]), so any state in the returned tool
 * is lost on retry. For stateless one-shot tools the factory form is still valid, but new
 * code should prefer the `tool = ...` overload to avoid the foot-gun.
 */
@Deprecated(
    "Use toolAgent(tool = ...) overload — factory recreates tool on each execute, breaking retry-safety",
    replaceWith = ReplaceWith("toolAgent(llm, executor, name, maxTurns, maxTurnsFn, eventListener, roundTripRetry, tool = TODO(\"singleton tool instance\"), transform, block)"),
)
inline fun <In, reified Tool : Any, Out> toolAgent(
    llm: Llm,
    executor: PromptExecutor,
    name: String = "${Tool::class.simpleName}Agent",
    maxTurns: Int = 10,
    noinline maxTurnsFn: ((In) -> Int)? = null,
    eventListener: AgentEventListener? = null,
    roundTripRetry: RetryPolicy? = null,
    frameworkInstructionsCacheStrategy: PromptCacheStrategy = PromptCacheStrategy.PIPELINE,
    crossinline factory: (ExecutionContext, In) -> Tool,
    crossinline transform: (ExecutionContext, Tool) -> Out,
    crossinline block: suspend PromptBuilder.(ExecutionContext, In, Tool) -> Unit
): Agent<In, Out> = toolCallingAgent<In, Tool>(
    llm, executor, name, maxTurns, maxTurnsFn, eventListener, roundTripRetry,
    frameworkInstructionsCacheStrategy = frameworkInstructionsCacheStrategy,
) { ec, input, tool -> block(ec, input, tool) }.mapInput { ec, input: In ->
    ToolCallingInput(input, factory(ec, input))
}.map { ec, tool: Tool ->
    transform(ec, tool)
}

/**
 * Retry-safe variant: takes a **single pre-built tool instance** that lives over the agent's
 * lifetime. The tool is captured in the agent closure once; every `Agent.execute` (including
 * retries after network errors) routes calls into the same tool. Combined with
 * [Builder.build] reading the tool's accumulated state, this is the recommended pattern for
 * stateful builders.
 *
 * See `todo/pipeline-builder-unification.md` for the design rationale.
 */
inline fun <In, reified Tool : Any, Out> toolAgent(
    llm: Llm,
    executor: PromptExecutor,
    name: String = "${Tool::class.simpleName}Agent",
    maxTurns: Int = 10,
    noinline maxTurnsFn: ((In) -> Int)? = null,
    eventListener: AgentEventListener? = null,
    roundTripRetry: RetryPolicy? = null,
    frameworkInstructionsCacheStrategy: PromptCacheStrategy = PromptCacheStrategy.PIPELINE,
    tool: Tool,
    crossinline transform: (ExecutionContext, Tool) -> Out,
    crossinline block: suspend PromptBuilder.(ExecutionContext, In, Tool) -> Unit
): Agent<In, Out> = toolAgent(
    llm, executor, name, maxTurns, maxTurnsFn, eventListener, roundTripRetry,
    frameworkInstructionsCacheStrategy = frameworkInstructionsCacheStrategy,
    factory = { _, _ -> tool },
    transform = transform,
    block = block,
)

/**
 * @deprecated See note on `factory` invocation in the base overload. Use the
